test('ticket export analysis: flagged statuses, period end, unstatused range, reconciliation', () => {
  const csv = [
    'ID,Status,Owning Team,Priority,Owner,Due Date,Created On,Resolved On',
    '1,🚩Open,Scrum1,High,Ali Hassan,2026-10-30,2026-10-01,',
    '2,🚩Open,Scrum1,,,,2026-10-02,',
    '3,Closed,Mobile Scrum,Low,Sara Ali,2026-10-10,2026-09-20,2026-10-05',
    '4,,Mobile Scrum,,,,2026-09-21,',
    '5,🚩Open,Unknown team,High,Omar Adel,2026-11-01,2026-10-20,',
  ].join('\n');
  const r = analyseTickets(csv, { groups: { Medical: ['Scrum1'], 'Non-Medical': ['Mobile Scrum'] }, periodEnd: '2026-10-08' });
  assert.equal(r.excludedAfterPeriod, 1);
  assert.equal(r.status.open, 2);
  assert.equal(r.status.unstatused, 1);
  assert.equal(r.triageRate, 50);
  assert.deepEqual(r.groups['Non-Medical'].openRateRange, [0, 50]);
  assert.ok(r.checks.every((c) => c.result === 'OK'));
  assert.ok(r.notes.some((n) => /non-letter/.test(n)));
});

test('KPI reply: A needs was and now figures, B needs a person and a date', () => {
  const good = `| # | KPI | Was | Now (21 Oct) |\n|---|---|---|---|\n| A1 | Open tickets | 442 | 355 |\n| A2 | Links | 0 | 63 |\n| A3 | x | 1 | 2 |\n| A4 | y | 3 | 4 |\n\n| # | KPI | Today | Target | Due | Owner |\n|---|---|---|---|---|---|\n${Array.from({ length: 6 }, (_, i) => `| B${i + 1} | Triage | 13% | 90% | 29 Oct | Mona Hassan |`).join('\n')}\n`;
  assert.equal(reviewKpiReply(good).findings.filter((f) => f.severity !== 'info').length, 0);
  const bad = good.replace('| A1 | Open tickets | 442 | 355 |', '| A1 | Open tickets | improved | better |').replace('| B1 | Triage | 13% | 90% | 29 Oct | Mona Hassan |', '| B1 | Triage | 13% | 90% | ongoing | PMO team |');
  const rules = reviewKpiReply(bad).findings.map((f) => f.rule);
  for (const r of ['Table A was/now', 'Table B owner', 'Table B due']) assert.ok(rules.includes(r), r);
  assert.match(kpiReplyTemplate({ scope: 'X' }), /### Table B/);
});

const EXEC = `## Team: Scrum 2
- **Headline:** A booking that fails part-way now reverses itself
- **Owns:** booking, visits, queue
- **Before:** a failed step stranded the patient
- **Mechanism:** booking → visit record → *rollback when a step fails* → queue
- **Outcomes:**
  1. **Reception.** No stranded bookings.
  2. **Patients.** Clear status.
  3. **Supervisors.** Same-day view.
- **Numbers:** Committed 22 · Delivered 20 · Completion 91% · Journeys rebuilt 3
- **Flag:** worth knowing | Two items moved to next week

> What "completion" means: delivered ÷ committed.`;

test('executive page parses, reviews clean, and renders an SVG mechanism', () => {
  const [t] = parseExecutive(EXEC);
  assert.equal(t.mechanism.find((s) => s.changed).text, 'rollback when a step fails');
  assert.equal(t.numbers.length, 4);
  assert.equal(reviewExecutive(EXEC).findings.length, 0);
  const html = renderExecutiveHtml(EXEC, { title: 'Week 42' });
  assert.match(html, /<svg[^>]+role="img"/);
  assert.match(html, /class="chg"/);
  const jargon = reviewExecutive(EXEC.replace('No stranded bookings.', 'Closed #12345 [FE] backlog items.')).findings.map((f) => f.rule);
  assert.ok(jargon.filter((r) => r === 'Executive vocabulary').length >= 1);
  assert.match(executiveTemplate({ teams: ['A', 'B'] }), /## Team: B/);
});

test('minutes keep the wording, separate PMO judgement, flag conflicts, apply naming', () => {
  const notes = `QA says the login bug is open but Mobile team says it was fixed in 4.2.
We agreed to retest on Sunday.
@Sara Ali please send the ADO link by 23/10.
My conclusion as PMO: this closes end of month.`;
  const m = buildMinutes(applyNaming(notes), { title: 'Mobile follow-up' });
  assert.equal(m.conflicts.length, 1);
  assert.equal(m.judgements.length, 1);
  assert.match(m.markdown, /> We agreed to retest on Sunday\./);
  assert.match(m.markdown, /## PMO judgement/);
  assert.doesNotMatch(m.markdown, /\bADO\b/);
  assert.equal(namingFindings('Synced from CRM to ADO').length, 2);
  assert.match(rcBlock({ rootCause: 'x' }), /^ROOT CAUSE: x\nSOLUTION: not set\nDEADLINE: not set$/);
});

test('ADO target validation and manifest without tags', () => {
  assert.deepEqual(validateTarget({ project: 'P', areaPath: 'P\\PMO' }), []);
  assert.ok(validateTarget({ project: 'P', areaPath: 'P\\PMO\\' }).some((p) => /separator/.test(p)));
  const m = buildManifest('## EP-01 · E\n\n#### US-001 · S\n- **Story:** As a x, I want y, so that z.\n- **Priority:** Must · **Phase:** 1A · **Team:** T\n- **Source:** S\n- **Acceptance criteria:**\n  1. Given a, when b, then c.\n', { project: 'P', areaPath: 'P\\A' });
  const req = m.items.find((i) => i.type === 'Requirement');
  assert.equal(req.tags, undefined);
  assert.match(req.description, /Priority:<\/b> Must/);
});

