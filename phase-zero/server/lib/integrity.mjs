// Report-integrity rules: the KPI-feedback rule, the "baseline" rule, "not done" vs "done, not evidenced",
// the five-block diagnostic standard, process notes in leadership documents, and the ticket-export
// helpers (flagged status values, unstatused rows, triage rate, reconciliation checks).
import { parseTables, plain } from './md.mjs';

const finding = (severity, rule, message, where = '') => ({ severity, rule, message, where });

// Constructions that describe intention or activity instead of a measurement.
export const BANNED_CONSTRUCTIONS = [
  /\bwe (have )?(started|initiated|begun)\b/i,
  /\bwe are (implementing|working on|aligned with)\b/i,
  /\bwe (closely )?(monitor|track)\b/i,
  /\bwe conduct periodic\b/i,
  /\bwe will continue to\b/i,
  /\bthese initiatives aim to\b/i,
  /\bthe plan covers\b/i,
];
// "Ongoing" / "In progress" are banned only as a status in their own right (a cell or line that says only that).
const BARE_STATUS = /^\s*(ongoing|in progress|on track)\.?\s*$/i;

const isDataLine = (l) => l.trim() && !/^\s*(```|---|>)/.test(l);

/** Lines (outside code blocks) with their 1-based numbers. */
function lines(text) {
  const out = [];
  let code = false;
  text.split('\n').forEach((l, i) => {
    if (l.trim().startsWith('```')) code = !code;
    else if (!code && isDataLine(l)) out.push([i + 1, l]);
  });
  return out;
}

export function kpiRuleSweep(text) {
  const findings = [];
  for (const [n, l] of lines(text)) {
    const re = BANNED_CONSTRUCTIONS.find((r) => r.test(l));
    if (re) findings.push(finding('major', 'KPI-feedback rule', `Activity statement, not a measurement: “${plain(l).trim().slice(0, 90)}”. Rewrite as a KPI moved (was → now, date) or a gap (today, target, due, named owner).`, `line ${n}`));
    if (l.trim().startsWith('|')) {
      const cells = l.split('|').map((c) => plain(c));
      if (cells.some((c) => BARE_STATUS.test(c))) findings.push(finding('major', 'KPI-feedback rule', '"Ongoing" / "In progress" used as a status by itself. Give the measured figure and its date.', `line ${n}`));
    } else if (BARE_STATUS.test(plain(l))) findings.push(finding('major', 'KPI-feedback rule', 'Bare status line with no figure.', `line ${n}`));
  }
  return findings;
}

/** "Baseline" is reserved for something approved and under change control. */
export function baselineRule(text) {
  const findings = [];
  for (const [n, l] of lines(text)) {
    const t = l.replace(/\bre-?baseline(s|d)?\b/gi, '').replace(/\b(functional|requirements|scope) baseline\b/gi, '');
    if (/\bbaseline\b/i.test(t) && !/\b(approved|signed[- ]off|under change control|no approved|not approved|pilot baseline|capture a .*baseline|baseline,? (then|and)|then track|pre-go-live baseline|kpi baseline)\b/i.test(t)) {
      findings.push(finding('major', 'Baseline rule', `“baseline” used without an approved target: “${plain(l).trim().slice(0, 80)}”. Say "reference dates (proposed)" or "actual vs actual" unless a baseline was approved.`, `line ${n}`));
    }
  }
  return findings;
}

/** A compliance gap must say whether it is "not done" or "done, not evidenced". */
export function evidenceRule(text) {
  const findings = [];
  for (const [n, l] of lines(text)) {
    if (/\b(non-compliant|missing evidence|no evidence|absent|not compliant)\b/i.test(l) && !/\b(not done|not evidenced|done, not evidenced)\b/i.test(l)) {
      findings.push(finding('minor', 'Not done vs not evidenced', 'Compliance gap without saying whether the work is not done or done but not evidenced. They need opposite fixes; ask the owner.', `line ${n}`));
    }
  }
  return findings;
}

/** Leadership documents carry no notes about how the document was produced. */
export function processNotesRule(text) {
  const findings = [];
  for (const [n, l] of lines(text)) {
    if (/\b(correction note|version change|this (report|document) was (generated|produced|prepared) (by|with)|generated by|regenerated|revised from the previous draft)\b/i.test(l)) {
      findings.push(finding('minor', 'No process notes', 'Notes about how the document was produced belong in PMO project docs, not in what goes to leadership.', `line ${n}`));
    }
  }
  return findings;
}

/** Same-line basis: two figures of one metric with no stated basis read as a contradiction. */
export function basisRule(text) {
  const findings = [];
  for (const [n, l] of lines(text)) {
    if (/documentation coverage/i.test(l) && /\d+(\.\d+)?\s*%/.test(l) && !/\b(audit|self-reported|measured|wiki-link)\b/i.test(l)) {
      findings.push(finding('minor', 'Metric basis', 'Documentation coverage quoted without its basis. Quote the measured audit figure, or show both with their bases on the same line.', `line ${n}`));
    }
    if (/\bcriticals?\b/i.test(l) && /\b\d{1,4}\b/.test(l) && !/\b(by team|by site|by view|team view|site view|definition)\b/i.test(l)) {
      findings.push(finding('info', 'Metric basis', 'Critical count quoted without saying which view (team, site, AI report) it is.', `line ${n}`));
    }
  }
  return findings;
}

// ------------------------------------------------------------------ the five-block diagnostic standard
export const DIAGNOSTIC_BLOCKS = [
  ['finding', /finding/i],
  ['evidence', /evidence/i],
  ['root cause', /root cause/i],
  ['corrective action', /corrective/i],
  ['preventive action', /preventive/i],
];

export function diagnosticStandard(text) {
  const findings = [];
  const tables = parseTables(text).filter((t) => t.headers.some((h) => /^finding/i.test(plain(h))));
  for (const t of tables) {
    const missing = DIAGNOSTIC_BLOCKS.filter(([, re]) => !t.headers.some((h) => re.test(plain(h)))).map(([k]) => k);
    if (missing.length) findings.push(finding('major', 'Diagnostic standard', `Findings table "${t.heading}" lacks: ${missing.join(', ')}.`, t.heading));
    const idx = Object.fromEntries(DIAGNOSTIC_BLOCKS.map(([k, re]) => [k, t.headers.findIndex((h) => re.test(plain(h)))]));
    for (const r of t.rows) {
      for (const [k] of DIAGNOSTIC_BLOCKS) {
        const i = idx[k];
        if (i >= 0 && !plain(r[i] || '').trim()) findings.push(finding('major', 'Diagnostic standard', `Empty "${k}" block.`, plain(r[0] || t.heading)));
      }
      const corr = idx['corrective action'] >= 0 ? plain(r[idx['corrective action']] || '') : '';
      if (corr && !/\d{1,2}\s+[A-Za-z]{3}|\d{4}-\d{2}-\d{2}|tbc/i.test(corr)) findings.push(finding('minor', 'Diagnostic standard', 'Corrective action carries no date.', plain(r[0] || '')));
      const rc = idx['root cause'] >= 0 ? plain(r[idx['root cause']] || '') : '';
      if (rc && !/\b(measurement|delivery)\b/i.test(rc)) findings.push(finding('info', 'Diagnostic standard', 'Root cause does not say whether it is a measurement fault or a delivery fault.', plain(r[0] || '')));
    }
  }
  return findings;
}

// ------------------------------------------------------------------ measurement helpers
/** The 5-point rule: >1 team moving >5 points the same direction means re-check the population. */
export function fivePointRule(series) {
  // series: { team: [older, ..., latest] } completion percentages
  const moves = Object.entries(series)
    .filter(([, v]) => v.length >= 2)
    .map(([team, v]) => {
      const prior = v.slice(-3, -1);
      const ref = prior.reduce((a, b) => a + b, 0) / prior.length;
      return { team, delta: +(v[v.length - 1] - ref).toFixed(1) };
    });
  const up = moves.filter((m) => m.delta > 5);
  const down = moves.filter((m) => m.delta < -5);
  const tripped = up.length > 1 ? up : down.length > 1 ? down : [];
  return { moves, tripped: tripped.length > 0, teams: tripped.map((m) => m.team) };
}

/** Ticket status values carry a flag character ("🚩Open"). Match on letters only. */
export const normaliseStatus = (s) => String(s || '').replace(/[^A-Za-z ]+/g, '').trim().toLowerCase();

const OPEN = new Set(['open', 'committed', 'on hold']);
const CLOSED = new Set(['closed', 'resolved', 'rejected', 'cancelled', 'canceled']);

function parseCsv(text) {
  const rows = [];
  let row = [];
  let cell = '';
  let q = false;
  const src = String(text).replace(/^﻿/, '');
  for (let i = 0; i < src.length; i++) {
    const c = src[i];
    if (q) {
      if (c === '"' && src[i + 1] === '"') { cell += '"'; i++; }
      else if (c === '"') q = false;
      else cell += c;
    } else if (c === '"') q = true;
    else if (c === ',' || c === '\t') { row.push(cell); cell = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && src[i + 1] === '\n') i++;
      row.push(cell); cell = '';
      if (row.some((x) => x.trim())) rows.push(row);
      row = [];
    } else cell += c;
  }
  row.push(cell);
  if (row.some((x) => x.trim())) rows.push(row);
  return rows;
}

const pick = (headers, ...names) => headers.findIndex((h) => names.some((n) => new RegExp(`^${n}$`, 'i').test(h.trim())));

/**
 * Ticket-export analysis. groups: { groupName: [teamNames...] } – teams not listed fall into "Unassigned".
 * Returns counts, triage rate, unstatused range and OK/MISMATCH reconciliation checks.
 */
export function analyseTickets(csvText, { groups = {}, periodEnd = null } = {}) {
  const [headers = [], ...rows] = parseCsv(csvText);
  const col = {
    status: pick(headers, 'status', 'request status'),
    team: pick(headers, 'owning team', 'team'),
    priority: pick(headers, 'priority'),
    owner: pick(headers, 'owner', 'assigned to', 'owning user'),
    due: pick(headers, 'due date', 'due'),
    raised: pick(headers, 'created on', 'raised', 'created', 'raised date'),
    category: pick(headers, 'category'),
    resolved: pick(headers, 'resolved on', 'resolved date', 'closed on'),
  };
  const teamToGroup = {};
  for (const [g, teams] of Object.entries(groups)) for (const t of teams) teamToGroup[t.toLowerCase()] = g;
  const end = periodEnd ? new Date(periodEnd) : null;

  let afterPeriod = 0;
  const kept = rows.filter((r) => {
    if (!end || col.raised < 0) return true;
    const d = new Date(r[col.raised]);
    if (!isNaN(d) && d > end) { afterPeriod++; return false; }
    return true;
  });

  const stat = { open: 0, closed: 0, unstatused: 0, other: 0 };
  const byGroup = {};
  let triaged = 0;
  const flagged = new Set();
  for (const r of kept) {
    const raw = col.status >= 0 ? r[col.status] || '' : '';
    if (/[^\x20-\x7E]/.test(raw)) flagged.add(raw.trim());
    const s = normaliseStatus(raw);
    const hasResolved = col.resolved >= 0 && String(r[col.resolved] || '').trim();
    const kind = !s && !hasResolved ? 'unstatused' : OPEN.has(s) ? 'open' : CLOSED.has(s) || (!s && hasResolved) ? 'closed' : 'other';
    stat[kind]++;
    const team = col.team >= 0 ? String(r[col.team] || '').trim() : '';
    const group = teamToGroup[team.toLowerCase()] || 'Unassigned';
    byGroup[group] ??= { open: 0, closed: 0, unstatused: 0, other: 0, total: 0 };
    byGroup[group][kind]++;
    byGroup[group].total++;
    if (kind === 'open') {
      const ok = [col.priority, col.owner, col.due].every((c) => c >= 0 && String(r[c] || '').trim());
      if (ok) triaged++;
    }
  }
  const rate = (n, d) => (d ? +((100 * n) / d).toFixed(1) : null);
  const groupsOut = Object.fromEntries(
    Object.entries(byGroup).map(([g, v]) => {
      const known = v.total - v.unstatused;
      return [g, { ...v, openRate: rate(v.open, known), openRateRange: v.unstatused ? [rate(v.open, v.total), rate(v.open + v.unstatused, v.total)] : null }];
    })
  );
  const sum = (k) => Object.values(byGroup).reduce((a, v) => a + v[k], 0);
  const checks = [
    ['Group totals = rows in period', sum('total') === kept.length, `${sum('total')} vs ${kept.length}`],
    ['Open + closed + other + unstatused = rows', stat.open + stat.closed + stat.other + stat.unstatused === kept.length, `${stat.open}+${stat.closed}+${stat.other}+${stat.unstatused} vs ${kept.length}`],
    ['Group open counts = open', sum('open') === stat.open, `${sum('open')} vs ${stat.open}`],
    ['Status column found', col.status >= 0, col.status >= 0 ? headers[col.status] : 'none'],
  ].map(([name, ok, detail]) => ({ name, result: ok ? 'OK' : 'MISMATCH', detail }));

  const notes = [];
  if (flagged.size) notes.push(`Status values carry non-letter characters (${[...flagged].slice(0, 3).join(', ')}); matched on letters only.`);
  if (afterPeriod) notes.push(`${afterPeriod} rows raised after the period end were excluded (the export date is not the period end).`);
  if (stat.unstatused) notes.push(`${stat.unstatused} rows have no status and no resolved date: quote open rates as a range where a group holds a material share.`);
  if (col.team < 0) notes.push('No team column: measure by category instead and say so.');

  return {
    rows: kept.length,
    excludedAfterPeriod: afterPeriod,
    status: stat,
    triageRate: rate(triaged, stat.open),
    triaged,
    groups: groupsOut,
    checks,
    notes,
    columns: Object.fromEntries(Object.entries(col).map(([k, i]) => [k, i >= 0 ? headers[i] : null])),
  };
}
