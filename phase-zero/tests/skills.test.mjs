test('diagnostic standard requires all five blocks, filled', () => {
  const ok = `## Findings\n| Finding | Evidence | Root cause | Corrective action | Preventive action |\n|---|---|---|---|---|\n| F1 | ID 1 | Measurement fault: tag | Retag by 29 Oct | Rule in method |\n`;
  assert.equal(diagnosticStandard(ok).filter((f) => f.severity !== 'info').length, 0);
  const bad = `## Findings\n| Finding | Evidence | Corrective action |\n|---|---|---|\n| F1 | | Fix it |\n`;
  const f = diagnosticStandard(bad);
  assert.ok(f.some((x) => /lacks: root cause, preventive action/.test(x.message)));
  assert.ok(f.some((x) => /Empty "evidence"/.test(x.message)));
});

test('5-point rule trips when more than one team moves the same way', () => {
  const r = fivePointRule({ S1: [97, 98, 88], S2: [96, 97, 85], S3: [95, 96, 97] });
  assert.equal(r.tripped, true);
  assert.deepEqual(r.teams, ['S1', 'S2']);
  assert.equal(fivePointRule({ S1: [97, 98, 88], S3: [95, 96, 97] }).tripped, false);
});

