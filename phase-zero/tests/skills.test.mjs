test('KPI-feedback rule flags activity statements and bare statuses', () => {
  const f = kpiRuleSweep('We have started the migration.\n| B1 | Triage | Ongoing |\nRevamp 28% → 41% (21 Oct).');
  assert.equal(f.length, 2);
  assert.ok(f.every((x) => x.rule === 'KPI-feedback rule'));
});

